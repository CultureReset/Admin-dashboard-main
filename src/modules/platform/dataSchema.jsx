const clip = (text, n = 60) => (text.length > n ? `${text.slice(0, n)}…` : text);

function cell(column, row) {
  const v = row[column.name];
  if (v === null || v === undefined || v === '') return <span className="faint">—</span>;
  if (isBool(column)) return v ? <Badge tone="success">Yes</Badge> : <Badge>No</Badge>;
  if (isStamp(column)) return formatDateTime(v);
  if (isDate(column)) return formatDate(v);
  if (isNumber(column)) return formatNumber(v);
  if (isUuid(column)) return <span className="mono faint" title={String(v)}>{String(v).slice(0, 8)}…</span>;
  if (isJson(column) || typeof v === 'object') {
    const text = Array.isArray(v) ? v.join(', ') : JSON.stringify(v);
    return <span className="mono faint" title={text}>{clip(text, 40)}</span>;
  }
  const text = String(v);
  if (text.length > 30 || text.includes('\n')) {
    return <span className="data-clip" title={text}>{text}</span>;
  }
  return text;
}

/** Table columns: the label column first, the id second, then the rest in schema order. */
export function buildTableColumns(columns, resource) {
  const rank = (c) => (c.name === resource.label_column ? 0 : c.name === resource.id_column ? 1 : 2);
  const ordered = [...columns].sort((a, b) => rank(a) - rank(b));
  return ordered.map((c, index) => ({
    key: c.name,
    header: humanize(c.name),
    sortable: !isJson(c) && !isArray(c),
    align: isNumber(c) ? 'right' : 'left',
    hideOn: index >= 3 ? 'narrow' : undefined,
    render: (row) =>
      c.name === resource.label_column ? (
        <span className="ui-cell-primary">{cell(c, row)}</span>
      ) : (
        cell(c, row)
      ),
  }));
}

export const rowLabel = (row, resource) => {
  const v = row?.[resource.label_column];
  return v !== null && v !== undefined && v !== '' ? String(v) : String(row?.[resource.id_column] ?? 'this row');
};
