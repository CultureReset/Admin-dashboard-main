/**
 * Turns the API's column list for a registry resource into form fields and
 * table columns. Nothing here names a table or a column: everything comes from
 * `columns` ([{ name, type, format, enum }], read off the database schema by
 * routes/admin-data.js) and the registry row (id_column, label_column).
 */

import { Badge } from '../../ui/primitives.jsx';
import { blankToNull, fields, formatDate, formatDateTime, formatNumber } from '../../lib/fields.jsx';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const INTEGER_FORMATS = new Set(['integer', 'bigint', 'smallint']);
const STAMPS = new Set(['created_at', 'updated_at']);
const LONG_TEXT = 80;

const fmt = (c) => String(c.format || '').toLowerCase();

export const isUuid = (c) => fmt(c) === 'uuid';
export const isBool = (c) => c.type === 'boolean' || fmt(c) === 'boolean';
export const isJson = (c) => ['json', 'jsonb'].includes(fmt(c)) || (c.type === 'object' && !c.enum);
export const isArray = (c) => c.type === 'array' || fmt(c).endsWith('[]');
export const isInteger = (c) => c.type === 'integer' || INTEGER_FORMATS.has(fmt(c));
export const isNumber = (c) => isInteger(c) || c.type === 'number' || ['numeric', 'real', 'double precision'].includes(fmt(c));
export const isDate = (c) => fmt(c) === 'date';
export const isTime = (c) => fmt(c).startsWith('time ') || fmt(c) === 'time';
export const isStamp = (c) => fmt(c).startsWith('timestamp');

/** "hero_image_url" → "Hero image url". */
export function humanize(name) {
  const text = String(name || '').replace(/_/g, ' ').trim();
  return text ? text[0].toUpperCase() + text.slice(1) : '';
}

/**
 * Is the primary key typed by the admin on create (a name, like a fact key)
 * rather than generated by the database (a uuid or a serial number)?
 */
export function idIsChosen(resource, columns) {
  const col = columns.find((c) => c.name === resource.id_column);
  if (!col) return false;
  return !isUuid(col) && !isNumber(col);
}

/** Columns the admin never edits: the primary key once it exists, and the two timestamps. */
export function isReadOnly(column, resource, { creating, chosenId }) {
  if (STAMPS.has(column.name)) return true;
  if (column.name === resource.id_column) return !(creating && chosenId);
  return false;
}

/** Plain-language server message for a column, e.g. null where a value is required. */
export function fieldErrorsFrom(error, columns) {
  const out = {};
  const names = new Set(columns.map((c) => c.name));
  const body = error?.body;

  // A structured map, if the API ever sends one.
  for (const key of ['errors', 'fields', 'field_errors', 'details']) {
    const map = body && typeof body === 'object' ? body[key] : null;
    if (map && typeof map === 'object' && !Array.isArray(map)) {
      for (const [name, message] of Object.entries(map)) {
        if (names.has(name)) out[name] = Array.isArray(message) ? message.join(' ') : String(message);
      }
    }
  }
  if (Object.keys(out).length) return out;

  // Today the API returns the database's own message in `error`; it quotes the
  // column it is unhappy about ('null value in column "label" …').
  const message = String(error?.message || '');
  for (const m of message.matchAll(/column "([^"]+)"/g)) {
    if (names.has(m[1])) out[m[1]] = friendly(message);
  }
  if (!Object.keys(out).length) {
    const key = message.match(/Key \(([^)]+)\)/)?.[1];
    if (key && names.has(key)) out[key] = friendly(message);
  }
  return out;
}

function friendly(message) {
  if (/not-null|null value/i.test(message)) return 'This field is required.';
  if (/duplicate key|already exists/i.test(message)) return 'That value is already taken.';
  if (/foreign key/i.test(message)) return 'That value does not match an existing record.';
  if (/invalid input syntax/i.test(message)) return 'That value is not in the right format.';
  return message;
}

/** Does this column hold long prose, going by what is actually in it? */
function looksLong(column, rows, row) {
  if (fmt(column) !== 'text') return false;
  const sample = [...(rows || []), row].filter(Boolean);
  return sample.some((r) => {
    const v = r[column.name];
    return typeof v === 'string' && (v.length > LONG_TEXT || v.includes('\n'));
  });
}

function fieldFor(column, { rows, row, chosenId, resource }) {
  const name = column.name;
  const label = humanize(name);
  const isId = name === resource.id_column;
  const extra = {};

  if (isId && chosenId) {
    return fields.text(name, label, {
      required: true,
      help: 'Chosen now and cannot be changed afterwards.',
      validate: (v) => (String(v ?? '').trim() === '' ? `${label} is required` : null),
    });
  }
  if (column.enum) return fields.select(name, label, column.enum, extra);
  if (isBool(column)) return fields.bool(name, label, extra);
  if (isInteger(column)) {
    return fields.number(name, label, {
      step: 1,
      validate: (v) => (v === null || v === undefined || v === '' || Number.isInteger(v) ? null : 'Must be a whole number'),
    });
  }
  if (isNumber(column)) {
    return fields.number(name, label, {
      validate: (v) => (v === null || v === undefined || v === '' || Number.isFinite(v) ? null : 'Must be a number'),
    });
  }
  if (isJson(column)) return fields.json(name, label, { help: 'JSON. Leave blank for none.' });
  if (isArray(column)) return fields.tags(name, label, { help: 'Comma-separated values.' });
  if (isStamp(column)) return fields.datetime(name, label);
  if (isDate(column)) return fields.date(name, label);
  if (isTime(column)) return fields.time(name, label);
  if (isUuid(column)) {
    return fields.text(name, label, {
      placeholder: '00000000-0000-0000-0000-000000000000',
      help: 'The id of a related record — copy it from that list. Leave blank for none.',
      validate: (v) => (!v || UUID.test(String(v).trim()) ? null : 'Not a valid id (expected a UUID)'),
    });
  }
  if (looksLong(column, rows, row)) return fields.textarea(name, label, { rows: 5 });
  return fields.text(name, label);
}

/** Form fields for create or edit — read-only columns are left out (shown as meta instead). */
export function buildFields(columns, resource, { creating, rows, row }) {
  const chosenId = idIsChosen(resource, columns);
  return columns
    .filter((c) => !isReadOnly(c, resource, { creating, chosenId }) || (creating && chosenId && c.name === resource.id_column))
    .map((c) => fieldFor(c, { rows, row, creating, chosenId, resource }));
}

/** The read-only columns of the row being edited, for the form's header. */
export function readOnlyFacts(columns, resource, row) {
  const chosenId = idIsChosen(resource, columns);
  return columns
    .filter((c) => isReadOnly(c, resource, { creating: false, chosenId }) && row?.[c.name] != null)
    .map((c) => ({
      name: c.name,
      label: humanize(c.name),
      value: isStamp(c) ? formatDateTime(row[c.name]) : String(row[c.name]),
    }));
}

/** Form values for a row (booleans and nulls normalised so controls stay controlled). */
export function toFormValues(columns, row) {
  const out = {};
  for (const c of columns) {
    const v = row?.[c.name];
    if (isJson(c)) out[c.name] = v == null ? '' : typeof v === 'string' ? v : JSON.stringify(v, null, 2);
    // A new row starts from the column's own database default (the API passes it along), so a toggle never
    // silently creates something switched off that the database would have switched on.
    else if (isBool(c)) out[c.name] = row == null && c.default != null ? c.default === true || c.default === 'true' : Boolean(v);
    else if (v === null || v === undefined) out[c.name] = isArray(c) ? [] : isNumber(c) ? null : '';
    else out[c.name] = v;
  }
  return out;
}

/**
 * Request body from submitted form values. On edit, blanks go as null so a
 * cleared field is cleared. On create they are left out, so a column with a
 * database default keeps it rather than being forced to null.
 */
export function toBody(values, columns, { creating }) {
  const body = blankToNull(values);
  for (const c of columns) {
    if (isArray(c) && Array.isArray(body[c.name]) && body[c.name].length === 0) body[c.name] = null;
  }
  if (creating) {
    for (const key of Object.keys(body)) {
      const col = columns.find((c) => c.name === key);
      if (body[key] === null && !(col && isBool(col))) delete body[key];
    }
  }
  return body;
}

